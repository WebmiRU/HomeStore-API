<?php

namespace App\Services;

use App\Models\Item;

/**
 * Количество предмета, который живёт по кодам.
 *
 * Обычно количество — число, которое человек ставит руками: сколько таких
 * вещей лежит на складе. Но у предмета с пометкой «списывать по коду» коды
 * принадлежат конкретным единицам: наклеили на пять одинаковых упаковок пять
 * разных наклеек и ведёте их по отдельности. Тогда количество и есть число
 * кодов, а ставить его руками — значит разойтись с наклейками.
 *
 * Поэтому у таких предметов количество считается, а не вводится:
 *
 *   - код добавили — добавилась единица;
 *   - код убрали — единица ушла.
 *
 * У остальных предметов ничего не меняется: несколько кодов у них означают
 * несколько наклеек одного товара, и количество остаётся числом, которое
 * человек знает сам. Без этого пересчёта такие предметы ломались бы при
 * каждом пересохранении.
 */
class CodedQuantity
{
    /**
     * Пересчитывает количество помеченного предмета по числу его кодов.
     *
     * Возвращает true, если количество изменилось, — вызывающий знает, что
     * предмет надо пересохранить.
     */
    public function refresh(Item $item): bool
    {
        if (! $item->release_code_on_writeoff) {
            return false;
        }

        // Именно столько кодов сейчас привязано к предмету. Считается по
        // базе, а не по присланному списку: высвобожденный при списании код
        // у предмета уже не числится, и после списания количество должно
        // уменьшиться само.
        $codes = $item->codes()->count();

        if ((int) $item->quantity === $codes) {
            return false;
        }

        $item->forceFill(['quantity' => $codes])->save();

        return true;
    }

    /**
     * Пересчитывает количество сразу после сохранения предмета с кодами.
     *
     * Присланное с формой количество у помеченного предмета игнорируется:
     * клиент всё равно отправляет поле, а верным числом остаётся то, что
     * посчитано по кодам. Иначе выставленное руками число разошлось бы с
     * наклейками, и списание пошло бы не по тем единицам.
     *
     * @param  list<string>  $codes  коды, какими предмет собран на сервере
     */
    public function refreshAfterSync(Item $item, array $codes): void
    {
        if (! $item->release_code_on_writeoff) {
            return;
        }

        // Ноль кодов — законное состояние помеченного предмета: он пуст, и
        // количество равно нулю. Раньше здесь был выход, и количество
        // оставалось прежним — предмет без кодов числился непустым, и списание
        // по нему проходило, как по обычному.
        $expected = count($codes);

        if ((int) $item->quantity === $expected) {
            return;
        }

        $item->forceFill(['quantity' => $expected])->save();
    }

    /**
     * Снимает присланное количество у помеченного предмета до сохранения.
     *
     * Сделано до update(): иначе значение успело бы записаться в базу и
     * осталось бы там, если бы пересчёт по кодам после syncCodes не
     * запустился — например, когда раздела codes в запросе не было.
     *
     * @param  array<string, mixed>  $data  проверенные поля запроса
     * @return array<string, mixed>
     */
    public function stripQuantity(Item $item, array $data): array
    {
        if ($item->release_code_on_writeoff || ($data['release_code_on_writeoff'] ?? false)) {
            unset($data['quantity']);
        }

        return $data;
    }
}
