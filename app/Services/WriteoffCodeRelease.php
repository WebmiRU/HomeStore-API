<?php

namespace App\Services;

use App\Models\Code;
use App\Models\Item;
use App\Models\StockOperationItem;
use App\Support\CodeFormat;

/**
 * Высвобождение кода при списании и возврат кода при откате.
 *
 * Обычно несколько кодов у предмета — это несколько наклеек одного товара:
 * наклеили на пять одинаковых упаковок, чтобы вести их по отдельности. Такие
 * коды переживают списание, ведь упаковки не вскрывали. Но бывает и другое:
 * код наклеен на конкретную единицу, которая ушла со склада, и держать его
 * занятым незачем. Отличает одно от другого пометка предмета
 * release_code_on_writeoff, и по умолчанию поведение прежнее.
 *
 * Код не удаляется, а отвязывается: списанный код может вернуться, ведь товар
 * возвращают, упаковку вскрывают и код наклеивают снова. Сломавшийся код
 * вернуть нечем, поэтому item_id обнуляется, а строка операции запоминает,
 * какому предмету код принадлежал. Откат операции возвращает его обратно.
 *
 * Высвобождается только код, по которому пришло списание, и только если у
 * предмета их больше одного: у предмета с единственным кодом освобождать
 * нечего, иначе предмет остался бы совсем без кода.
 */
class WriteoffCodeRelease
{
    /**
     * Высвободится ли код при списании по строке операции.
     *
     * Отдельный метод нужен проверяющему проходу: списание по коду снимает
     * ровно одну единицу, и понять это надо ДО применения, а не после.
     */
    public function willRelease(Item $item, string $scannedCode): bool
    {
        return $this->findReleasable($item, $scannedCode) !== null;
    }

    /**
     * Высвобождает код предмета, если предмет на это настроен.
     *
     * Возвращает код, который нужно записать в released_code_id строки
     * операции, либо null — если предмет не настроен, кодов не больше одного
     * либо списанного кода у предмета нет.
     */
    public function releaseFor(Item $item, string $scannedCode): ?Code
    {
        $code = $this->findReleasable($item, $scannedCode);

        if ($code === null) {
            return null;
        }

        $code->forceFill(['item_id' => null])->save();

        return $code;
    }

    /**
     * Код строки, который можно высвободить, либо null.
     *
     * Условия те же, что и в releaseFor: если здесь код найдётся, а там
     * нет, строка операции запомнит несуществующий код, и откат будет искать
     * то, чего не было.
     */
    private function findReleasable(Item $item, string $scannedCode): ?Code
    {
        if (! $item->release_code_on_writeoff) {
            return null;
        }

        $codes = $item->codes()->orderBy('sort')->get();

        // Последний код высвобождается наравне с остальными. Раньше здесь стояло
        // «меньше двух кодов не отпускаем», чтобы предмет не остался вовсе без
        // кода; но у помеченного предмета код и есть единица, и его количество
        // считается по кодам. Запрет давал ровно то, на что натыкается человек:
        // количество уходило в ноль, а последний код оставался висеть — и
        // предмет с нулевым остатком продолжал находиться сканированием.
        // Пополнить такой предмет можно, наклеив новый код: коды заводятся в
        // карточке, и это осмысленнее, чем держать наклейку на пустой полке.
        if ($codes->isEmpty()) {
            return null;
        }

        // Ищем по обоим написаниям кода: исторические коды предметов
        // записаны с дефисами, коды из наборов безымянных этикеток — без.
        $candidates = CodeFormat::candidates($scannedCode);

        return $codes->first(fn (Code $row): bool => in_array($row->code, $candidates, true));
    }

    /**
     * Возвращает коды предмету при откате списания.
     *
     * Возвращаются только те коды, что были высвобождены самой откатываемой
     * строкой, и по одному на возвращаемую единицу: списали три кода одной
     * строкой, вернули одну единицу — вернулся один код.
     *
     * @param  array<int, array{row: StockOperationItem, quantity: int}>  $prepared
     * @return array<int, array{code: Code, item: Item}>  коды, которые надо вернуть предмету
     */
    public function restore(array $prepared): array
    {
        $restored = [];

        foreach ($prepared as $entry) {
            /** @var StockOperationItem $row */
            $row = $entry['row'];

            if ($row->released_code_id === null) {
                continue;
            }

            $code = Code::find($row->released_code_id);

            if ($code === null) {
                // Код удалён как осиротевший — вернуть нечего, но строку
                // от этого надо очистить, иначе возврат попытался бы снова.
                $row->forceFill(['released_code_id' => null])->save();

                continue;
            }

            $item = Item::find($row->item_id);

            if ($item === null) {
                continue;
            }

            // Код мог за это время получить другой предмет: возвращать его
            // силой значило бы снять чужую привязку. Такой код просто
            // остаётся, где он есть, а предмет остаётся без кода.
            if ($code->item_id !== null && $code->item_id !== $item->id) {
                continue;
            }

            // Возвращённый код уходит в конец списка кодов предмета: он был
            // последним среди списанных, и порядок после возврата должен
            // отражать, что вернулось позже.
            $sort = (int) $item->codes()->max('sort');
            $code->forceFill(['item_id' => $item->id, 'sort' => $sort + 1])->save();

            $row->forceFill(['released_code_id' => null])->save();

            $restored[] = ['code' => $code, 'item' => $item];
        }

        return $restored;
    }
}
