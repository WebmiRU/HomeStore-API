<?php

namespace App\Support;

use Illuminate\Support\Facades\DB;

/**
 * Системный шаблон мини-этикеток: DataMatrix без подписи.
 *
 * Общий для всех пользователей, но не редактируемый и не удаляемый: на нём
 * держится генерация наборов безымянных этикеток, и произвольная правка
 * геометрии сломала бы уже напечатанные наклейки.
 *
 * Геометрия: ячейка 16 мм, символ 20x20 модулей по 0,5 мм = 10 мм, белое
 * поле 3 мм с каждой стороны (6X при минимуме ISO 16022 в 2X). Поле заложено
 * с запасом сверх стандарта: наклейки режут руками, и неровный срез иначе
 * либо зацепит символ, либо срежет тихую зону. На A4 с полями 10 мм
 * помещается 11x17 = 187 этикеток.
 *
 * Размер символа задаёт размер модуля (10 / 20 = 0,5 мм), а 0,5 мм —
 * единственное значение, которое одновременно ровно 4 точки при 203 dpi и
 * ровно 6 точек при 300 dpi. Увеличивать поле можно только расширяя ячейку,
 * сжимать символ нельзя: 0,4 мм — это 3,2 точки на 203 dpi, то есть печать
 * с растром.
 *
 * Определение живёт здесь, а не в сидере, потому что его должны создавать
 * два разных механизма: миграция (на любом развёрнутом окружении, где
 * сидеры не запускают) и сидер (при локальной сборке с нуля).
 */
class SystemLabelPreset
{
    /**
     * Геометрия и признаки системного шаблона. font_id подставляется
     * в sync(): при show_text = false шрифт по большому счёту не рисуется,
     * но toOptions() ссылается на него как на запасной вариант.
     */
    public static function definition(): array
    {
        return [
            'title'              => 'Мини-этикетки 16×16 (без текста)',
            'page_width'         => 210.0,
            'page_height'        => 297.0,
            'page_margin_top'    => 10.0,
            'page_margin_right'  => 10.0,
            'page_margin_bottom' => 10.0,
            'page_margin_left'   => 10.0,
            'cell_width'         => 16.0,
            'cell_height'        => 16.0,
            'cell_pad_top'       => 3.0,
            'cell_pad_right'     => 3.0,
            'cell_pad_bottom'    => 3.0,
            'cell_pad_left'      => 3.0,
            'barcode_position'   => 'left',
            'barcode_text_gap'   => 0.0,
            'barcode_size'       => 10.0,
            'show_text'          => false,
            'font_size_min'      => 5.0,
            'font_size_max'      => 24.0,
            'font_size_step'     => 0.5,
            'line_height_factor' => 1.25,
            'is_system'          => true,
            'user_id'            => null,
        ];
    }

    /**
     * Создаёт системный шаблон либо приводит существующий к актуальной
     * геометрии. Идемпотентно: и миграция, и сидер зовут это на своём
     * окружении, и повторный прогон не должен плодить копии.
     *
     * Ищем по is_system, а не по названию: системный шаблон по определению
     * один, а название входит в саму конфигурацию (12x12 -> 16x16), и поиск
     * по нему после переименования завёл бы второй шаблон, оставив старый
     * неуправляемым.
     */
    public static function sync(): void
    {
        $definition = self::definition() + [
            'font_id' => DB::table('font')->where('key', 'dejavusanscondensedb')->value('id'),
        ];

        $existing = DB::table('label_preset')->where('is_system', true)->first();

        if ($existing !== null) {
            DB::table('label_preset')
                ->where('id', $existing->id)
                ->update($definition + ['updated_at' => now()]);

            return;
        }

        DB::table('label_preset')
            ->insert($definition + ['created_at' => now(), 'updated_at' => now()]);
    }
}
