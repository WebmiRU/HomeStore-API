<?php

namespace App\Support;

/**
 * Единицы измерения, которые получает новый пользователь.
 *
 * Список минимальный и намеренно общий: без него первое же числовое
 * свойство («Длина», «Вес») пришлось бы сначала завести единицу, иначе
 * значение сохранилось бы голым числом без «мм» и «кг». Дальше пользователь
 * дописывает свои — это его персональный справочник, общий список ему не
 * мешает, потому что показывается рядом с его единицами, а не вместо них.
 *
 * Определение живёт здесь, а не в сидере, потому что его должны создавать
 * два разных механизма: UserRegistrationService при регистрации и сидер при
 * локальной сборке с нуля.
 */
class DefaultUnits
{
    /**
     * @return array<int, array{title_short: string, title_full: string}>
     */
    public static function definition(): array
    {
        return [
            ['title_short' => 'шт', 'title_full' => 'штука'],
            ['title_short' => 'мм', 'title_full' => 'миллиметр'],
            ['title_short' => 'кг', 'title_full' => 'килограмм'],
            ['title_short' => 'л',  'title_full' => 'литр'],
        ];
    }
}
