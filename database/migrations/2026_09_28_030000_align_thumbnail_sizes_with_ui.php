<?php

use App\Enums\ImageCrop;
use App\Enums\ImageFormat;
use App\Models\Thumbnail;
use Illuminate\Database\Migrations\Migration;

/**
 * Каталог миниатюр под три варианта на каждое место: 1×, 1.5× и 2×.
 *
 * Размеры измерены в браузере: пропсы и CSS расходятся (в списках передаётся
 * 40 и 72, а на экране 38 и 70), и ориентироваться надо на второе — именно
 * эти пиксели получает экран.
 *
 * Место → размер на экране → строка каталога (×1, ×1.5, ×2):
 *   дерево содержимого, предметы     22 →  22,  33,  44
 *   дерево содержимого, узлы         28 →  28,  42,  56
 *   списки предметов, хранилищ,
 *   пользователей, логотипы          38 →  38,  57,  76
 *   аватар в шапке                    56 →  56,  84, 112
 *   результаты поиска                 70 →  70, 105, 140
 *   вкладка «Изображения», ячейка     80 →  80, 120, 160
 *   карточка предмета                 84 →  84, 126, 168
 *   аватар и логотип в карточке      120 → 120, 180, 240
 *   просмотр фотографии             800 → 800, 1200, 1600
 *
 * Вариантов втрое больше строк, чем мест: браузер сам выбирает нужный по
 * экрану, а лишние он не качает. Вариант, который больше оригинала,
 * клиент в srcset не отдаёт — увеличивать нечего, только портить.
 *
 * Стороны берутся потолком от «размер × коэффициент»: 33, 57, 105, 126 и
 * прочие не круглые, зато ровно соответствуют тому, что рисуется, и
 * округление вверх не оставляет ни одного экрана с мылом.
 */
return new class extends Migration
{
    /**
     * Сторона квадратной миниатюры → обрезка.
     *
     * Одной стороне соответствует ровно одна обрезка: cover — там, где
     * кадр режется по квадрату (фото предмета, аватар), contain — там, где
     * важна целиком картинка (логотип производителя, просмотр фотографии).
     */
    private const COVER_SIZES = [
        22, 28, 33, 38, 42, 44, 56, 57, 70, 76, 84,
        105, 112, 120, 126, 140, 168, 180, 240,
    ];

    /** Логотип вписывается, а не обрезается: края у логотипа и есть логотип. */
    private const CONTAIN_SIZES = [38, 57, 76, 80, 120, 160, 180, 240, 800, 1200, 1600];

    /**
     * Каталог до пересчёта — на случай отката.
     *
     * Стороны выведены из мест, которые были заведены раньше: 22–28 в дереве
     * содержимого, 40 и 56 в списках и шапке, 72 в поиске, 84 в карточке
     * предмета, 120 в карточке, 800 в просмотре. Каждая брала по одной строке
     * ×2, отсюда и лестница 50…250.
     */
    private const PREVIOUS = [
        '50x50_cover', '60x60_cover', '80x80_cover', '100x100_cover', '120x120_cover',
        '150x150_cover', '160x160_contain', '170x170_cover', '240x240_cover',
        '80x80_contain', '240x240_contain', '800x800_contain',
    ];

    public function up(): void
    {
        $this->sync();
    }

    public function down(): void
    {
        Thumbnail::query()->whereIn('key', self::PREVIOUS)->delete();
    }

    /**
     * Приводит каталог к списку мест: недостающее заводит, лишнее убирает.
     *
     * Каталог принадлежит этому списку целиком — других его потребителей в
     * приложении нет, а строка, которую никто не запрашивает, только занимает
     * место в таблице и в файлах хранилища.
     */
    private function sync(): void
    {
        foreach (self::COVER_SIZES as $side) {
            $this->put($side, ImageCrop::Cover);
        }

        foreach (self::CONTAIN_SIZES as $side) {
            $this->put($side, ImageCrop::Contain);
        }

        $keys = array_merge(
            array_map(static fn (int $side): string => "{$side}x{$side}_cover", self::COVER_SIZES),
            array_map(static fn (int $side): string => "{$side}x{$side}_contain", self::CONTAIN_SIZES),
        );

        Thumbnail::query()->whereNotIn('key', $keys)->delete();
    }

    private function put(int $side, ImageCrop $crop): void
    {
        // Ключ собираем склейкой, а не подстановкой в строку: значение
        // перечисления внутри «{$…}» не разворачивается, и в базу уезжал
        // ключ «22x22_{crop->value}» — каталог из тридцати строк, не
        // совпадающих ни с одним запросом клиента.
        $key = $side . 'x' . $side . '_' . $crop->value;

        Thumbnail::updateOrCreate(
            ['key' => $key],
            [
                'format' => ImageFormat::Avif,
                'width'  => $side,
                'height' => $side,
                'crop'   => $crop,
            ]
        );
    }
};
